const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  --tex-${k}: ${v};`)
    .join("\n")}\n}`

const selectorFor = (stock, theme) => {
  const isDefault = stock === "bond"
  if (theme === "day")
    return isDefault
      ? `:root,\n:root[data-stock="${stock}"]`
      : `:root[data-stock="${stock}"]`
  return isDefault
    ? `:root[data-theme="night"]`
    : `:root[data-stock="${stock}"][data-theme="night"]`
}

const out = [
  block(":root", NEUTRAL.day),
  block(':root[data-theme="night"]', NEUTRAL.night),
  ...Object.entries(STOCKS).flatMap(([stock, themes]) =>
    ["day", "night"].map((theme) => {
      const {
        mottle,
        flecks: [count, palette],
      } = themes[theme]
      return block(selectorFor(stock, theme), {
        mottle: tinted(1201, 0.0035, 4, 41, ...mottle),
        flecks: flecks(719, count, 29, palette),
        // For dense screens (base.css): the same specks, none under a pixel across.
        "flecks-sharp": flecks(719, count, 29, palette, 0.6),
      })
    }),
  ),
]

const file = new URL(
  "../../src/fineliner/styles/textures.generated.css",
  import.meta.url,
)
writeFileSync(
  file,
  `/* Generated by tools/paper/build-textures.mjs. Edit the layers there, then rerun it. */\n${out.join("\n\n")}\n`,
)
console.log(
  `wrote ${file.pathname}: ${Object.keys(STOCKS).length} stocks, 5 layers each, flecks also sharp`,
)
