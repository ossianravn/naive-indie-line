// Builds the Fineliner Naïve fonts from the kit's skeleton alphabet, capitals only (lowercase types the same capitals),
// every Latin-script European language, three takes per glyph that rotate through `calt`:
//   Fineliner Naïve Sans   the pen as a typeface: round-ended monoline
//   Fineliner Naïve Inline      a contrasted serif: thick strokes as two outlines, thin strokes as one line
//   Fineliner Naïve Inline Fill the tint between Inline's outlines, to set under it in a second colour
//   Fineliner Naïve Tramline    the drawn Tramline: every stroke three parallel lines in a fine pen
// Each face comes in four styles: Regular, Bold (the same hand with a broader pen), Italic (the skeleton slanted 10°
// before the pen draws it, so the pen stays round: a slanted hand, not a cursive) and Bold Italic. Every style draws
// with the same seeds, so a letter wobbles the same way in all four.
// Writes public/fonts/<file>.otf and .woff2 (for download and design tools) and the kit's styles/*.generated.css,
// which carry the WOFF2 inside them so an install needs no font files: the Regulars in line-sans, inline and
// tramline, the other styles in their *-styles companions, opt-in. The same sources build the same bytes.
//
//   node tools/fonts/build.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { createJiti } from "jiti"
import { glyphSet } from "./glyphset.mjs"
import { buildFamily, fontFace, toPath } from "./family.mjs"
import { inlineGlyph } from "./inline.mjs"
import { outline, wobble } from "./outline.mjs"
import { tramlineGlyph } from "./tramline.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const { prng, seedOf } = await createJiti(import.meta.url).import(
  path.join(root, "src/fineliner/pen/seed.ts"),
)
const { drawn, chars, codes } = await glyphSet(root)
const SCALE = 7 // skeleton cap height 100 → 700 units
const TAKES = 3
const out = path.join(root, "public/fonts")
fs.mkdirSync(out, { recursive: true })
const kb = (bytes) => `${(bytes.length / 1024).toFixed(0)} KB`

const STYLES = [
  { name: "Regular", file: "", weight: 400, italic: false },
  { name: "Bold", file: "-bold", weight: 700, italic: false },
  { name: "Italic", file: "-italic", weight: 400, italic: true },
  { name: "Bold Italic", file: "-bold-italic", weight: 700, italic: true },
]
// tan 10°, the italic's slant, leaning about half the cap height (350 units) so the letter keeps its place.
const SLANT = 0.17633
const lean = (style, toFont) =>
  style.italic
    ? (pt) => {
        const [x, y] = toFont(pt)
        return [x + (y - 350) * SLANT, y]
      }
    : toFont
const ps = (base, style) => `${base}-${style.name.replace(" ", "")}`

/** Write a family's files in a style and report their size. */
async function write(spec) {
  const { otf, woff2 } = await buildFamily({
    ...spec,
    chars,
    codes,
    takes: TAKES,
  })
  const file = `${spec.file}${spec.style.file}`
  fs.writeFileSync(path.join(out, `${file}.otf`), otf)
  fs.writeFileSync(path.join(out, `${file}.woff2`), woff2)
  console.log(
    `${spec.family} ${spec.style.name}: ${chars.length} glyphs × ${TAKES} takes, otf ${kb(otf)}, woff2 ${kb(woff2)}`,
  )
  return woff2
}
/** The Regular's stylesheet and its styles' companion. */
const sheets = (file, about, faces) => {
  css(`${file}.generated.css`, about, faces.slice(0, faces.length / 4))
  css(
    `${file}-styles.generated.css`,
    `${about}: Bold, Italic and Bold Italic`,
    faces.slice(faces.length / 4),
  )
}
const css = (file, about, faces) =>
  fs.writeFileSync(
    path.join(root, `src/fineliner/styles/${file}`),
    `/* Generated by tools/fonts/build.mjs: ${about} (MIT). Do not edit by hand. */\n${faces.join("")}`,
  )

// Fineliner Naïve Sans: every stroke swept by one round pen 32 units wide (50 in Bold).
{
  const SIDE = 62
  const HAND = { wave: 170, amp: 4.5, tremor: 0 }
  const family = "Fineliner Naïve Sans"
  const faces = []
  for (const style of STYLES) {
    const PEN = style.weight === 700 ? 25 : 16
    const toFont = lean(style, ([x, y]) => [
      x * SCALE + SIDE + PEN,
      (100 - y) * SCALE,
    ])
    const glyphPath = (g, rand) => {
      const strokes = [...g.s, ...(g.m ?? [])].map((s) => {
        const pts = s.map(toFont)
        const closed =
          pts.length > 3 &&
          Math.hypot(pts[0][0] - pts.at(-1)[0], pts[0][1] - pts.at(-1)[1]) < 1
        return wobble(pts, closed, rand, HAND)
      })
      const dots = (g.d ?? []).map(([x, y, r]) => [...toFont([x, y]), r])
      return toPath(outline(strokes, dots, PEN))
    }
    const woff2 = await write({
      family,
      style,
      file: "fineliner-naive-sans",
      postScript: ps("FinelinerNaiveSans", style),
      description:
        "The Fineliner pen as a typeface: monoline capitals with a gentle hand, three takes per letter.",
      advance: (c) => Math.round(drawn[c].w * SCALE + 2 * (SIDE + PEN)),
      // Seeds keep the old font names so the letters stay the same.
      path: (c, take) =>
        glyphPath(drawn[c], prng(seedOf(`naive-indie-line-sans:${c}:${take}`))),
    })
    faces.push(fontFace(family, woff2, style))
  }
  sheets("line-sans", `${family}, the pen as a typeface`, faces)
}

// Fineliner Naïve Inline and its Fill: one wobbled drawing per glyph and take, split into the pen's lines and the tint.
// Bold draws the thick parts wider and the lines in a broader pen.
{
  const lineFamily = "Fineliner Naïve Inline"
  const fillFamily = "Fineliner Naïve Inline Fill"
  const [lineFaces, fillFaces] = [[], []]
  for (const style of STYLES) {
    const bold = style.weight === 700
    const FACE = {
      T: bold ? 50 : 38,
      h: bold ? 11 : 8,
      serif: bold ? 30 : 26,
      tick: 58,
      dot: bold ? 27 : 22,
      hand: { wave: 190, amp: 3.5, tremor: 0 },
    }
    const SIDE = 44 + FACE.T + FACE.serif
    const toFont = lean(style, ([x, y]) => [
      x * SCALE + SIDE,
      (100 - y) * SCALE,
    ])
    const cache = new Map()
    const drawing = (c, take) => {
      const key = `${c}:${take}`
      if (!cache.has(key))
        cache.set(
          key,
          inlineGlyph(
            drawn[c],
            c,
            // Seeds keep the old font names so the letters stay the same.
            prng(seedOf(`naive-indie-inline:${c}:${take}`)),
            toFont,
            FACE,
          ),
        )
      return cache.get(key)
    }
    const shared = {
      description:
        "The Fineliner pen as a contrasted serif: thick strokes drawn as two outlines, three takes per letter.",
      advance: (c) => Math.round(drawn[c].w * SCALE + 2 * SIDE),
      space: 300,
    }
    const lines = await write({
      ...shared,
      style,
      family: lineFamily,
      file: "fineliner-naive-inline",
      postScript: ps("FinelinerNaiveInline", style),
      path: (c, take) => toPath(outline(drawing(c, take).lines, [], FACE.h)),
    })
    const fill = await write({
      ...shared,
      style,
      family: fillFamily,
      file: "fineliner-naive-inline-fill",
      postScript: ps("FinelinerNaiveInlineFill", style),
      description: `${shared.description} The tint, to set under Fineliner Naïve Inline.`,
      path: (c, take) => toPath(outline([], [], 0, drawing(c, take).fills)),
    })
    lineFaces.push(fontFace(lineFamily, lines, style))
    fillFaces.push(fontFace(fillFamily, fill, style))
  }
  const about = `${lineFamily} and its tint, ${fillFamily}`
  css("inline.generated.css", about, [lineFaces[0], fillFaces[0]])
  css("inline-styles.generated.css", `${about}: Bold, Italic and Bold Italic`, [
    ...lineFaces.slice(1),
    ...fillFaces.slice(1),
  ])
}

// Fineliner Naïve Tramline: three lines 32 units apart, swept by a pen 13 units wide, so the paper shows between them;
// Bold sets them 41 apart in a pen 21 wide.
{
  const family = "Fineliner Naïve Tramline"
  const faces = []
  for (const style of STYLES) {
    const bold = style.weight === 700
    const PEN = bold ? 10.5 : 6.5
    const FACE = {
      gap: bold ? 5.9 : 4.6,
      over: 4.5,
      tilt: 2.2,
      lift: 2,
      dot: 3.4,
      hand: { wave: 260, amp: 5, tremor: 0 },
    }
    const SIDE = 103
    const toFont = lean(style, ([x, y]) => [
      x * SCALE + SIDE,
      (100 - y) * SCALE,
    ])
    const woff2 = await write({
      family,
      style,
      file: "fineliner-naive-tramline",
      postScript: ps("FinelinerNaiveTramline", style),
      description:
        "The Fineliner pen's Tramline lettering as a typeface: every stroke three parallel lines, three takes per letter.",
      advance: (c) => Math.round(drawn[c].w * SCALE + 2 * SIDE),
      path: (c, take) => {
        const { strokes, dots } = tramlineGlyph(
          drawn[c],
          // Seeds keep the old font names so the letters stay the same.
          prng(seedOf(`naive-indie-tramline:${c}:${take}`)),
          toFont,
          FACE,
        )
        return toPath(outline(strokes, dots, PEN))
      },
    })
    faces.push(fontFace(family, woff2, style))
  }
  sheets("tramline", `${family}, the pen's tramlines as a typeface`, faces)
}
