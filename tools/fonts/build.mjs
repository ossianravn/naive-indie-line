// Builds the Naïve Indie fonts from the kit's skeleton alphabet, capitals only (lowercase types the same capitals),
// every Latin-script European language, three takes per glyph that rotate through `calt`:
//   Naïve Indie Line Sans   the pen as a typeface: round-ended monoline
//   Naïve Indie Inline      a contrasted serif: thick strokes as two outlines, thin strokes as one line
//   Naïve Indie Inline Fill the tint between Inline's outlines, to set under it in a second colour
// Writes public/fonts/<file>.otf and .woff2 (for download and design tools) and the kit's styles/*.generated.css,
// which carry the WOFF2 inside them so an install needs no font files. The same sources build the same bytes.
//
//   node tools/fonts/build.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { createJiti } from "jiti"
import { glyphSet } from "./glyphset.mjs"
import { buildFamily, fontFace, toPath } from "./family.mjs"
import { inlineGlyph } from "./inline.mjs"
import { outline, wobble } from "./outline.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const { prng, seedOf } = await createJiti(import.meta.url).import(
  path.join(root, "src/fineliner/pen/seed.ts"),
)
const { drawn, chars, codes } = await glyphSet(root)
const SCALE = 7 // skeleton cap height 100 → 700 units
const TAKES = 3
const out = path.join(root, "public/fonts")
fs.mkdirSync(out, { recursive: true })
const kb = (bytes) => `${(bytes.length / 1024).toFixed(0)} KB`

/** Write a family's files and report its size. */
async function write(spec) {
  const { otf, woff2 } = await buildFamily({
    ...spec,
    chars,
    codes,
    takes: TAKES,
  })
  fs.writeFileSync(path.join(out, `${spec.file}.otf`), otf)
  fs.writeFileSync(path.join(out, `${spec.file}.woff2`), woff2)
  console.log(
    `${spec.family}: ${chars.length} glyphs × ${TAKES} takes, otf ${kb(otf)}, woff2 ${kb(woff2)}`,
  )
  return woff2
}
const css = (file, about, faces) =>
  fs.writeFileSync(
    path.join(root, `src/fineliner/styles/${file}`),
    `/* Generated by tools/fonts/build.mjs: ${about} (MIT). Do not edit by hand. */\n${faces.join("")}`,
  )

// Naïve Indie Line Sans: every stroke swept by one round pen 32 units wide.
{
  const PEN = 16
  const SIDE = 62
  const HAND = { wave: 170, amp: 4.5, tremor: 0 }
  const toFont = ([x, y]) => [x * SCALE + SIDE + PEN, (100 - y) * SCALE]
  const glyphPath = (g, rand) => {
    const strokes = [...g.s, ...(g.m ?? [])].map((s) => {
      const pts = s.map(toFont)
      const closed =
        pts.length > 3 &&
        Math.hypot(pts[0][0] - pts.at(-1)[0], pts[0][1] - pts.at(-1)[1]) < 1
      return wobble(pts, closed, rand, HAND)
    })
    const dots = (g.d ?? []).map(([x, y, r]) => [...toFont([x, y]), r])
    return toPath(outline(strokes, dots, PEN))
  }
  const family = "Naïve Indie Line Sans"
  const woff2 = await write({
    family,
    file: "naive-indie-line-sans",
    postScript: "NaiveIndieLineSans-Regular",
    description:
      "The Fineliner pen as a typeface: monoline capitals with a gentle hand, three takes per letter.",
    advance: (c) => Math.round(drawn[c].w * SCALE + 2 * (SIDE + PEN)),
    path: (c, take) =>
      glyphPath(drawn[c], prng(seedOf(`naive-indie-line-sans:${c}:${take}`))),
  })
  css("line-sans.generated.css", `${family}, the pen as a typeface`, [
    fontFace(family, woff2),
  ])
}

// Naïve Indie Inline and its Fill: one wobbled drawing per glyph and take, split into the pen's lines and the tint.
{
  const FACE = {
    T: 38,
    h: 8,
    serif: 26,
    tick: 58,
    dot: 22,
    hand: { wave: 190, amp: 3.5, tremor: 0 },
  }
  const SIDE = 44 + FACE.T + FACE.serif
  const toFont = ([x, y]) => [x * SCALE + SIDE, (100 - y) * SCALE]
  const cache = new Map()
  const drawing = (c, take) => {
    const key = `${c}:${take}`
    if (!cache.has(key))
      cache.set(
        key,
        inlineGlyph(
          drawn[c],
          c,
          prng(seedOf(`naive-indie-inline:${c}:${take}`)),
          toFont,
          FACE,
        ),
      )
    return cache.get(key)
  }
  const shared = {
    description:
      "The Fineliner pen as a contrasted serif: thick strokes drawn as two outlines, three takes per letter.",
    advance: (c) => Math.round(drawn[c].w * SCALE + 2 * SIDE),
    space: 300,
  }
  const lineFamily = "Naïve Indie Inline"
  const fillFamily = "Naïve Indie Inline Fill"
  const lines = await write({
    ...shared,
    family: lineFamily,
    file: "naive-indie-inline",
    postScript: "NaiveIndieInline-Regular",
    path: (c, take) => toPath(outline(drawing(c, take).lines, [], FACE.h)),
  })
  const fill = await write({
    ...shared,
    family: fillFamily,
    file: "naive-indie-inline-fill",
    postScript: "NaiveIndieInlineFill-Regular",
    description: `${shared.description} The tint, to set under Naïve Indie Inline.`,
    path: (c, take) => toPath(outline([], [], 0, drawing(c, take).fills)),
  })
  css("inline.generated.css", `${lineFamily} and its tint, ${fillFamily}`, [
    fontFace(lineFamily, lines),
    fontFace(fillFamily, fill),
  ])
}
