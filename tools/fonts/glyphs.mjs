/** Points on an ellipse from a0 to a1 degrees (0 right, 90 down), every 4 degrees, so curves stay smooth when large. */
export function A(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(8, Math.round(Math.abs(a1 - a0) / 4))
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)]
  })
}
const O = (cx, cy, rx, ry) => A(cx, cy, rx, ry, 0, 360)
const mirror = (w, strokes) => strokes.map((s) => s.map(([x, y]) => [w - x, y]))
const shift = (dx, strokes) =>
  strokes.map((s) => s.map(([x, y]) => [x + dx, y]))
/** Round a polyline's corners (Chaikin), for shapes easier to give as a few points than as arcs. */
function smooth(points, rounds = 3) {
  let pts = points
  for (let k = 0; k < rounds; k++)
    pts = [
      pts[0],
      ...pts.slice(0, -1).flatMap((p, i) => {
        const q = pts[i + 1]
        return [
          [p[0] * 0.75 + q[0] * 0.25, p[1] * 0.75 + q[1] * 0.25],
          [p[0] * 0.25 + q[0] * 0.75, p[1] * 0.25 + q[1] * 0.75],
        ]
      }),
      pts[pts.length - 1],
    ]
  return pts
}
